# OOP stands for Object-Oriented Programming.

# OOP is a programming paradigm in which we use objects in code to map real-world scenarios.

# Main advantages of OOP:
# 1. Redundancy decreases.
# 2. Reusability increases.

# Redundancy:
# Means repetition of the same code again and again.
# OOP helps to reduce code repetition.

# Reusability:
# Means writing code once and using it multiple times.
# OOP makes code reusable.

# Programming Paradigms:
# 1. Procedural Programming
# 2. Functional Programming
# 3. Object-Oriented Programming (OOP)

# OOP focuses on objects.
# Objects help us represent real-world entities.

# IMPORTANT:
# OOP = Less Redundancy + More Reusability