# QUE 1 


# WHILE LOOP

n = 8
sum = 0
i = 1
while i <= n:
    sum += i
    i += 1
print("total sum = ", sum)


# FOR LOOP

n = 8
sum = 0
for i in range(1, n+1):
    sum += i
print("total sum = ", sum)





