# Creating a list
my_list = [10, 20, 30, 40, 50]

# Creating a tuple
my_tuple = (10, 20, 30, 40, 50)

# Length
print(len(my_list))
print(len(my_tuple))

# Maximum and Minimum
print(max(my_list))
print(min(my_list))

print(max(my_tuple))
print(min(my_tuple))

# Updating list
my_list[1] = 100
print(my_list)

# Updating tuple
my_tuple[1] = 100
print(my_tuple)